    /// <summary>
    /// One flange drilling and minimum-thickness configuration from the
    /// Reece flange dimension guide. Values are strings so unavailable
    /// combinations and dual imperial/metric dimensions remain faithful to
    /// the published source.
    /// </summary>
    public sealed class FlangeDimensionConfiguration
    {
        public string Standard { get; set; }
        public int NominalSizeMm { get; set; }
        public string ClassOrTable { get; set; }
        public string OutsideDiameterMm { get; set; }
        public string PitchCircleDiameterMm { get; set; }
        public string NumberOfHoles { get; set; }
        public string HoleDiameter { get; set; }
        public string BoltDiameter { get; set; }
        public string CastIronThicknessMm { get; set; }
        public string DuctileIronThicknessMm { get; set; }
        public string CopperAlloyThicknessMm { get; set; }
        public string SteelThicknessMm { get; set; }
    }

    /// <summary>
    /// Built-in read-only flange configurations. Keeping the row model
    /// mutable allows a future editor or persisted override layer to reuse it.
    /// </summary>
    public static class FlangeDimensionConfigurationCatalog
    {
        public static IReadOnlyList<FlangeDimensionConfiguration> All { get; } =
            Load();

        private static IReadOnlyList<FlangeDimensionConfiguration> Load()
        {
            List<FlangeDimensionConfiguration> configurations =
                new List<FlangeDimensionConfiguration>();

            string[] lines = Data.Split(
                new[] { '\r', '\n' },
                StringSplitOptions.RemoveEmptyEntries);

            foreach (string line in lines)
            {
                string[] values = line.Split('|');

                if (values.Length != 12)
                    throw new InvalidOperationException(
                        "Invalid built-in flange configuration row.");

                configurations.Add(new FlangeDimensionConfiguration
                {
                    Standard = values[0],
                    NominalSizeMm = int.Parse(values[1]),
                    ClassOrTable = values[2],
                    OutsideDiameterMm = values[3],
                    PitchCircleDiameterMm = values[4],
                    NumberOfHoles = values[5],
                    HoleDiameter = values[6],
                    BoltDiameter = values[7],
                    CastIronThicknessMm = values[8],
                    DuctileIronThicknessMm = values[9],
                    CopperAlloyThicknessMm = values[10],
                    SteelThicknessMm = values[11]
                });
            }

            return configurations.AsReadOnly();
        }

